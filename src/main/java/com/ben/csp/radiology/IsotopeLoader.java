package com.ben.csp.radiology;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Loads the REKORD layer-1 nuclide data (half-lives, decay modes, emissions,
 * decay daughters) into {@link IsotopeRegistry}.
 *
 * <p>The data file is generated by {@code tools/radiology/fetch_decay_data.py}
 * from the IAEA Nuclear Data Services API, which serves the evaluated ENSDF
 * library. Nothing in the file is hand-typed: every half-life, branching ratio
 * and emission line is an evaluated measurement, and each isotope carries the
 * ENSDF publication date and author string so a value can be checked against the
 * evaluated file. That is what the project rule "nothing is guessed" requires of
 * this layer.
 *
 * <p>Why this layer can be built to full fidelity while the release model cannot:
 * decay data is measurement. The contested parts of a source term -- how much of
 * an inventory left the building, and how it was divided between gas, aerosol
 * and fuel particles -- are not in this file and must not be invented here.
 *
 * <p>Loading is reported, not silently tolerated. {@link #load()} returns the
 * number of isotopes loaded and {@link #problems()} lists every isotope whose
 * record was unusable, so a missing or truncated data file shows up as a named
 * failure rather than as an empty registry that quietly produces no dose.
 */
public final class IsotopeLoader {

    public static final String RESOURCE = "/data/csp/radiology/isotopes.json";

    private static final List<String> PROBLEMS = new ArrayList<>();
    private static boolean loaded;

    private IsotopeLoader() {}

    /** Loads the data file once. Safe to call repeatedly. */
    public static synchronized int load() {
        if (loaded) {
            return IsotopeRegistry.getInstance().size();
        }
        loaded = true;
        Map<String, Isotope> parsed = new LinkedHashMap<>();
        try (InputStream in = IsotopeLoader.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                PROBLEMS.add("data resource missing: " + RESOURCE);
                return 0;
            }
            JsonObject root = JsonParser.parseReader(
                new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            for (JsonElement e : root.getAsJsonArray("isotopes")) {
                Isotope isotope = parse(e.getAsJsonObject());
                if (isotope != null) {
                    parsed.put(isotope.symbol(), isotope);
                }
            }
        } catch (Exception e) {
            PROBLEMS.add("failed to read " + RESOURCE + ": " + e);
            return 0;
        }
        IsotopeRegistry.getInstance().loadIsotopes(parsed);
        return parsed.size();
    }

    private static Isotope parse(JsonObject o) {
        String nuclide = str(o, "nuclide");
        if (nuclide.isEmpty()) {
            PROBLEMS.add("isotope entry without a nuclide name");
            return null;
        }
        boolean stable = o.has("stable") && o.get("stable").getAsBoolean();
        Double halfLife = dbl(o, "halfLifeSeconds");
        if (!stable && halfLife == null) {
            // An unstable nuclide with no half-life is a broken record. Accepting
            // it would let it decay at zero rate (or divide by zero later), and
            // either way the registry would hold a physical lie.
            PROBLEMS.add(nuclide + ": unstable but halfLifeSeconds missing");
            return null;
        }

        Map<String, Double> decayModes = new LinkedHashMap<>();
        for (JsonElement m : arr(o, "decayModes")) {
            JsonObject mo = m.getAsJsonObject();
            String mode = str(mo, "mode");
            Double pct = dbl(mo, "percent");
            if (!mode.isEmpty()) {
                decayModes.put(mode, pct == null ? Double.NaN : pct / 100.0);
            }
        }

        List<Isotope.DecayProduct> products = new ArrayList<>();
        for (JsonElement p : arr(o, "decayProducts")) {
            JsonObject po = p.getAsJsonObject();
            products.add(new Isotope.DecayProduct(
                str(po, "nuclide"), branchOf(decayModes, po)));
        }

        List<Isotope.Emission> emissions = new ArrayList<>();
        for (JsonElement em : arr(o, "emissions")) {
            JsonObject eo = em.getAsJsonObject();
            String type = str(eo, "type");
            Double energy = dbl(eo, "energyMeV");
            Double intensity = dbl(eo, "intensity");
            if (type.isEmpty() || energy == null || energy <= 0.0) {
                PROBLEMS.add(nuclide + ": emission with no usable energy");
                continue;
            }
            emissions.add(new Isotope.Emission(
                type, energy, intensity == null ? 0.0 : intensity));
        }

        return new Isotope(
            displayName(nuclide),
            nuclide,
            halfLife == null ? Double.POSITIVE_INFINITY : halfLife,
            Collections.unmodifiableMap(decayModes),
            Collections.unmodifiableList(products),
            Collections.unmodifiableList(emissions),
            str(o, "group"),
            stable,
            str(o, "source"),
            ensdf(o),
            o.has("isomer") && o.get("isomer").getAsBoolean());
    }

    /** Branching ratio for a daughter, summed over the modes that lead to it. */
    private static double branchOf(Map<String, Double> modes, JsonObject product) {
        double sum = 0.0;
        boolean any = false;
        for (JsonElement m : arr(product, "modes")) {
            Double b = modes.get(m.getAsString());
            if (b != null && !b.isNaN()) {
                sum += b;
                any = true;
            }
        }
        return any ? sum : Double.NaN;
    }

    /** "Cs137" -> "Caesium-137" as far as the symbol allows; the ticker uses it. */
    private static String displayName(String nuclide) {
        int split = nuclide.length();
        for (int i = 0; i < nuclide.length(); i++) {
            if (Character.isDigit(nuclide.charAt(i))) {
                split = i;
                break;
            }
        }
        return nuclide.substring(0, split) + "-" + nuclide.substring(split);
    }

    private static String ensdf(JsonObject o) {
        if (!o.has("ensdf")) {
            return "";
        }
        JsonObject e = o.getAsJsonObject("ensdf");
        return str(e, "publicationCutoff") + " (" + str(e, "authors") + ")";
    }

    /** Isotopes whose record was unusable, with the reason. Empty means clean. */
    public static List<String> problems() {
        return Collections.unmodifiableList(PROBLEMS);
    }

    private static String str(JsonObject o, String key) {
        return o.has(key) && !o.get(key).isJsonNull() ? o.get(key).getAsString() : "";
    }

    private static Double dbl(JsonObject o, String key) {
        return o.has(key) && !o.get(key).isJsonNull() ? o.get(key).getAsDouble() : null;
    }

    private static JsonArray arr(JsonObject o, String key) {
        return o.has(key) && o.get(key).isJsonArray()
            ? o.getAsJsonArray(key) : new JsonArray();
    }

    /** Convenience for callers that only need one nuclide and expect it to exist. */
    public static Isotope require(String nuclide) {
        load();
        Isotope i = IsotopeRegistry.getInstance().getIsotope(nuclide);
        if (i == null) {
            throw new IllegalStateException(
                "isotope " + nuclide + " not in REKORD data ("
                    + IsotopeRegistry.getInstance().size() + " loaded, problems: "
                    + PROBLEMS + ")");
        }
        return i;
    }

    /** Groups as the fetcher classified them, for the contamination model. */
    public static Map<String, List<Isotope>> byGroup() {
        load();
        Map<String, List<Isotope>> out = new HashMap<>();
        for (Isotope i : IsotopeRegistry.getInstance().all()) {
            out.computeIfAbsent(i.group(), k -> new ArrayList<>()).add(i);
        }
        return out;
    }
}
